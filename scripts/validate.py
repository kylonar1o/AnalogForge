#!/usr/bin/env python3
"""Run the reference validation suite and write docs/validation.md.

Every number in docs/validation.md is produced by this script from real
ngspice + SKY130 simulations; re-run it to reproduce them:

    python scripts/validate.py            # ~2-4 minutes on 4 cores
"""

from __future__ import annotations

import datetime as dt
import math
import platform
import sys
import time
from pathlib import Path

from analogforge import __version__
from analogforge.backends.ngspice import ngspice_version
from analogforge.core.design import evaluate
from analogforge.designs import get_design
from analogforge.flows.executor import evaluate_points
from analogforge.flows.optimize import run_optimization, variables_from_design
from analogforge.flows.sweep import pvt_points, worst_case
from analogforge.metrics.oscillator import leeson
from analogforge.pdks.sky130 import find_sky130

ROOT = Path(__file__).resolve().parents[1]


def g(x, d=4):
    return "n/a" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x:.{d}g}"


def main() -> int:
    t0 = time.time()
    out = ["# Validation results", "",
           f"Generated by `scripts/validate.py` on {dt.date.today()} - AnalogForge {__version__}, "
           f"ngspice-{ngspice_version()}, Python {platform.python_version()}, SKY130 models: "
           f"{find_sky130().origin if find_sky130() else 'missing'}.", "",
           "All values below are simulator output (ngspice + SkyWater SKY130, corner tt, 27 C unless stated).", ""]

    # 1 RC low-pass ----------------------------------------------------------------------------
    r = evaluate("rc_lowpass")
    out += ["## 1. Simulator sanity: RC low-pass (YAML design)", "",
            "| quantity | simulated | analytic 1/(2πRC) | error |", "|---|---|---|---|",
            f"| f-3dB | {g(r.metrics['f3db'], 6)} Hz | {g(r.metrics['f3db_expected'], 6)} Hz | {g(r.metrics['error_pct'], 3)} % |", ""]

    # 2 op-amp --------------------------------------------------------------------------------
    r = evaluate("two_stage_opamp")
    m, h = r.metrics, r.extra["hand_estimates"]
    out += ["## 2. Two-stage Miller op-amp (built-in design, default sizing)", "",
            "| metric | simulated | small-signal hand estimate (simulated gm, gds) |", "|---|---|---|",
            f"| DC gain | {g(m['gain_db'])} dB | {g(h['gain_db'])} dB (A1·A2 = gm2/(gds2+gds4)·gm6/(gds6+gds7)) |",
            f"| UGBW | {g(m['ugbw'] / 1e6)} MHz | {g(h['gbw'] / 1e6)} MHz (gm1/2πCc) |",
            f"| phase margin | {g(m['phase_margin'])} ° | – |",
            f"| gain margin | {g(m['gain_margin'])} dB | – |",
            f"| slew rate (follower) | {g(m['slew_rate'] / 1e6)} V/µs | {g(h['slew_rate_internal'] / 1e6)} V/µs (Itail/Cc, internal limit) |",
            f"| 1 % settling | {g(m['settling_time'] * 1e9)} ns | – |",
            f"| PSRR+ | {g(m['psrr_db'])} dB | – |",
            f"| power | {g(m['power'] * 1e6)} µW | – |",
            f"| systematic offset | {g(m['offset'] * 1e3)} mV | – |", ""]

    # 3 VCO ---------------------------------------------------------------------------------------
    r = evaluate("lc_vco", options={"tuning_points": 7, "phase_noise": "isf", "isf_points": 12, "pss": True})
    m, ex = r.metrics, r.extra
    rp = get_design("lc_vco").rp(r.params)
    lee = leeson([1e6], m["f_osc"], m["q_tank"], m["amplitude_diff"] ** 2 / (4 * rp), 2.0)[0]
    out += ["## 3. Cross-coupled LC VCO (built-in design, default sizing)", "",
            "### Frequency - three independent estimates", "",
            "| method | f_osc |", "|---|---|",
            f"| zero crossings of v(outp)-v(outn) (transient) | {g(m['f_osc'] / 1e9, 6)} GHz |",
            f"| FFT peak (transient) | {g(m['f_fft'] / 1e9, 6)} GHz |",
            f"| ngspice PSS (shooting) | {g(m['f_pss'] / 1e9, 6)} GHz ({g(ex.get('pss_vs_tran_pct'), 3)} % vs transient) |", "",
            f"Differential amplitude {g(m['amplitude_diff'])} V, power {g(m['power'] * 1e3)} mW, start-up "
            f"{g(m['startup_time'] * 1e9)} ns, gm·R_P = {g(m['loop_gain_startup'])}.", "",
            "### Tuning curve", "", "| VTUNE (V) | f (GHz) |", "|---|---|"]
    for v, f in zip(ex["tuning"]["vtune"], ex["tuning"]["f"]):
        out.append(f"| {v:.2f} | {g(f / 1e9 if f else None, 5)} |")
    out += ["", f"Tuning range {g(m['tuning_range_pct'])} %, K_VCO,max {g(m['kvco_max'] / 1e6)} MHz/V.", "",
            "### Phase noise (ISF method, 12 phases × 2 injection sites × ±Δq = 48 transients)", "",
            f"* Γ_rms(tank) = {g(ex['isf_gamma_rms']['tank'])} (theory for a sinusoidal LC oscillator: 1/√2 = 0.707)",
            f"* Γ_rms(M1 drain-source) = {g(ex['isf_gamma_rms']['m1'])}",
            f"* noise contributions: tank {g(100 * ex['phase_noise']['contributions']['tank'], 3)} %, "
            f"cross-coupled pair {g(100 * ex['phase_noise']['contributions']['m1'], 3)} %",
            f"* L(1 MHz) = **{g(m['pn_1M'])} dBc/Hz** (ISF) vs {g(lee)} dBc/Hz (Leeson, F = 2, Q = {g(m['q_tank'], 3)})",
            f"* FoM = {g(m['fom'])} dB, FoM_T = {g(m['fom_t'])} dB", "",
            "ISF samples (Γ normalised to q_max):", "", "| phase (rad) | Γ_tank | Γ_M1 |", "|---|---|---|"]
    for ph, a, b in zip(ex["isf"]["tank"]["phase_rad"], ex["isf"]["tank"]["gamma"], ex["isf"]["m1"]["gamma"]):
        out.append(f"| {ph:.3f} | {a:+.3f} | {b:+.3f} |")

    # 4 YAML LC ----------------------------------------------------------------------------------
    r = evaluate("lc_vco_simple")
    m = r.metrics
    out += ["", "## 4. YAML LC oscillator vs. hand analysis", "",
            "| quantity | simulated | hand estimate |", "|---|---|---|",
            f"| frequency | {g(m['f_osc'] / 1e9, 5)} GHz | {g(m['f_lc'] / 1e9, 5)} GHz (1/2π√LC, no parasitics) |",
            f"| differential amplitude | {g(m['amplitude_diff'])} V | {g(m['amplitude_hand'])} V ((4/π)·I_tail·R_P) |", ""]

    # 5 PVT ---------------------------------------------------------------------------------------
    d = get_design("lc_vco")
    pts = pvt_points(["tt", "ff", "ss", "sf", "fs"], [0.9, 1.0, 1.1], [-40, 27, 125])
    res = evaluate_points(d, pts, options={"tuning_points": 0, "phase_noise": "leeson"})
    wc = worst_case(d, res, pts)
    out += ["## 5. VCO over PVT (5 corners × 3 supplies × 3 temperatures = 45 runs)", "",
            f"Failed runs: {sum(not x.ok for x in res)}; oscillating: {sum(bool(x.extra.get('oscillating')) for x in res)}/45.", "",
            "| metric | min | max | worst case at |", "|---|---|---|---|"]
    for k in ("f_osc", "amplitude_diff", "power", "pn_1M", "fom"):
        v = wc[k]
        out.append(f"| {k} | {g(v['min'])} | {g(v['max'])} | {v['worst_at'] or '–'} |")

    # 6 optimization -------------------------------------------------------------------------
    d = get_design("two_stage_opamp")
    opt = run_optimization(d, variables_from_design(d, ["W1", "W6", "CC", "IBIAS"]), "max:ugbw",
                           ["phase_margin >= 60", "gain_db >= 60", "power <= 0.4e-3"], "bayes", 24, 0,
                           options={"tran": False, "psrr": False})
    b = opt.best
    out += ["", "## 6. Bayesian optimization of the op-amp (24 evaluations, seed 0)", "",
            "Objective: maximise UGBW subject to PM ≥ 60°, gain ≥ 60 dB, power ≤ 0.4 mW.", "",
            f"Best point (feasible = {b.feasible}): " + ", ".join(f"{k} = {v:.4g}" for k, v in b.params.items()), "",
            f"UGBW {g(b.metrics['ugbw'] / 1e6)} MHz, PM {g(b.metrics['phase_margin'])} °, gain {g(b.metrics['gain_db'])} dB, "
            f"power {g(b.metrics['power'] * 1e6)} µW (default design: see section 2).", ""]
    out.append(f"_Total run time: {time.time() - t0:.0f} s._")
    path = ROOT / "docs" / "validation.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path} in {time.time() - t0:.0f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
